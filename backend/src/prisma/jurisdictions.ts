// Country/jurisdiction profiles for the demo data seeder.
//
// Adding a new country is a matter of appending one object to `PROFILES`. The
// seeder reads the active profile from `DEMO_COUNTRY` (env) or the option passed
// to `seedDemoData()` and uses it for names, phones, addresses, tax IDs, banks,
// currencies, locales and payroll/utility presets. Defaults to Kenya (`KE`) so
// existing demos and tests are unchanged.

export interface JurisdictionProfile {
  code: string; // ISO-3166-1 alpha-2
  name: string;
  currency: string; // ISO-4217
  locale: string; // BCP-47
  timezone: string; // IANA
  /**
   * The consumption tax rate, as a percentage: VAT in most of the world, GST in
   * some, sales tax in the United States — where there is no national rate at
   * all, which is why this is 0 there and not 5.
   *
   * It belongs to the country because it is the country's. A tariff priced in
   * pounds and taxed at the Kenyan rate of 16% is a number nobody can reconcile,
   * and a seeded utility bill that is wrong in a way only the tax authority
   * would notice is worse than one that is obviously a demo.
   */
  vatRate: number;
  phoneCountryCode: string; // E.164 country code, e.g. +254
  phonePrefixes: string[]; // carrier prefixes (subscriber portion)
  phoneSubscriberLength: number;
  firstNames: string[];
  lastNames: string[];
  corporateNames: string[];
  streets: string[];
  cities: string[];
  districts: string[];
  postalCode: () => string;
  taxIdLabel: string;
  taxIdGenerator: () => string;
  banks: string[];
  bankBranches: string[];
  propertyPrefixes: string[];
  propertySuffixes: string[];
  weekendDays: number[];
  domains: string[];
  utilityTariffs: { type: string; unit: string; rate: number }[];
  /**
   * The monthly residential rent band for this market, in the local currency.
   *
   * A rent is a local fact, not a constant: 45,000 KES and 45,000 ZAR are
   * different worlds, and a market seeded with Kenya's figures in Johannesburg
   * (or vice versa) reads as a demo that has never been to the country it is
   * pretending to be. The band is wide because a market has a fringe — a
   * two-bedroom in the middle of the band is a plausible ask; the ends are the
   * studio and the penthouse.
   */
  monthlyRent: { min: number; max: number };
}

