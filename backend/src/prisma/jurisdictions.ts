export const PROFILES: Record<string, JurisdictionProfile> = Object.fromEntries(
  profiles.map((p) => [p.code, p]),
);

export const DEFAULT_COUNTRY = 'KE';

let activeProfile: JurisdictionProfile = PROFILES[DEFAULT_COUNTRY];

export function setActiveProfile(code: string): JurisdictionProfile {
  const profile = PROFILES[code.toUpperCase()];
  if (!profile) throw new Error(`Unknown jurisdiction profile: ${code}`);
  activeProfile = profile;
  return activeProfile;
}

export function getActiveProfile(): JurisdictionProfile {
  return activeProfile;
}

export function getProfile(code: string): JurisdictionProfile {
  const p = PROFILES[code.toUpperCase()];
  if (!p) throw new Error(`Unknown jurisdiction profile: ${code}`);
  return p;
}

export function randomFrom<T>(arr: T[]): T {
  return arr[r(arr.length)];
}

export function randomPhone(
  profile: JurisdictionProfile = activeProfile,
): string {
  const prefix = randomFrom(profile.phonePrefixes);
  const restLen = Math.max(1, profile.phoneSubscriberLength - prefix.length);
  const rest = String(
    Math.floor(Math.random() * Math.pow(10, restLen)),
  ).padStart(restLen, '0');
  // remove country code leading zero handling: just concatenate
  return `${profile.phoneCountryCode}${prefix}${rest}`.replace(/\s+/g, '');
}

export function randomName(
  profile: JurisdictionProfile = activeProfile,
): string {
  return `${randomFrom(profile.firstNames)} ${randomFrom(profile.lastNames)}`;
}

export function randomAddress(
  profile: JurisdictionProfile = activeProfile,
): string {
  const n = Math.floor(Math.random() * 999) + 1;
  return `${n} ${randomFrom(profile.streets)}, ${randomFrom(profile.cities)}`;
}

export function randomEmail(
  name: string,
  profile: JurisdictionProfile = activeProfile,
): string {
  const domain = randomFrom(profile.domains);
  return `${name.toLowerCase().replace(/\s+/g, '.')}@${domain}`;
}

export function randomTaxId(
  profile: JurisdictionProfile = activeProfile,
): string {
  return profile.taxIdGenerator();
}

export function randomPropertyName(
  index: number,
  profile: JurisdictionProfile = activeProfile,
): string {
  const prefix = randomFrom(profile.propertyPrefixes);
  const suffix = randomFrom(profile.propertySuffixes);
  return `${prefix} ${suffix} ${index}`;
}

export function randomCorporateName(
  profile: JurisdictionProfile = activeProfile,
): string {
  return randomFrom(profile.corporateNames);
}

export function randomBank(
  profile: JurisdictionProfile = activeProfile,
): string {
  return randomFrom(profile.banks);
}

export function randomBankBranch(
  profile: JurisdictionProfile = activeProfile,
): string {
  return randomFrom(profile.bankBranches);
}

export function randomCity(
  profile: JurisdictionProfile = activeProfile,
): string {
  return randomFrom(profile.cities);
}

export function randomDistrict(
  profile: JurisdictionProfile = activeProfile,
): string {
  return randomFrom(profile.districts);
}

export function randomPostalCode(
  profile: JurisdictionProfile = activeProfile,
): string {
  return profile.postalCode();
}
