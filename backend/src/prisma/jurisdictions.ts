export const PROFILES: Record<string, JurisdictionProfile> = Object.fromEntries(
  profiles.map((p) => [p.code, p]),
);

export const DEFAULT_COUNTRY = 'KE';

/**
 * The markets the demo data covers, in the order the seeder creates them.
 *
 * This is the shortlist of places with real demand for a property management
 * system: the big rental markets (US, UK, Canada, Australia, Germany, France),
 * the fast-growing ones (India, China, Japan, South Korea, Brazil, Mexico), the
 * GCC (United Arab Emirates), and — in Africa — **Kenya and South Africa only**,
 * because those are the two African markets this product actually targets.
 *
 * Every code here must have a profile in `PROFILES`; `demoMarkets()` fails
 * loudly when the two disagree, because a market in the list with no profile
 * behind it is a market the demo silently skips.
 */
export const DEMO_MARKETS: string[] = [
  'KE',
  'ZA',
  'US',
  'GB',
  'CA',
  'AU',
  'DE',
  'FR',
  'IN',
  'CN',
  'JP',
  'KR',
  'BR',
  'MX',
  'AE',
];

/**
 * The demo markets, with the primary market moved to the front.
 *
 * The primary market is the one that gets the two full demo organizations
 * (Rohi with the whole dataset, Westhill as the starter); the rest get a
 * market organization each.
 */
export function demoMarkets(primary: string = DEFAULT_COUNTRY): string[] {
  const head = primary.toUpperCase();
  const rest = DEMO_MARKETS.filter((code) => code !== head);
  return PROFILES[head] ? [head, ...rest] : [...DEMO_MARKETS];
}

/**
 * The domain an organization in this market would use for its own addresses.
 *
 * Each profile carries an `example.<tld>` domain as its last entry precisely so
 * this can be derived from it — an organization in Johannesburg gets a `.co.za`
 * address and one in Seoul a `.co.kr` one, without a second table of domains
 * to keep in step with the profiles.
 */
export function orgEmailDomain(profile: JurisdictionProfile): string {
  const last = profile.domains[profile.domains.length - 1] ?? 'example.com';
  return last.startsWith('example.') ? last.slice('example.'.length) : last;
}

/**
 * A plausible monthly rent for this market, in the local currency.
 *
 * Whole units, because a rent of 45,000.50 is not a thing anybody asks in any
 * of these markets, and a decimal that survives the round trip through
 * `Decimal(10,2)` only makes the demo look like it was never read.
 */
export function rentInRange(profile: JurisdictionProfile): number {
  const { min, max } = profile.monthlyRent;
  return Math.round(min + Math.random() * (max - min));
}

let activeProfile: JurisdictionProfile = PROFILES[DEFAULT_COUNTRY];

export function setActiveProfile(code: string): JurisdictionProfile {
  const profile = PROFILES[code.toUpperCase()];
  if (!profile) throw new Error(`Unknown jurisdiction profile: ${code}`);
  activeProfile = profile;
  return activeProfile;
}

export function getActiveProfile(): JurisdictionProfile {
  return activeProfile;
}

export function getProfile(code: string): JurisdictionProfile {
  const p = PROFILES[code.toUpperCase()];
  if (!p) throw new Error(`Unknown jurisdiction profile: ${code}`);
  return p;
}

/**
 * The tariff for a utility in this jurisdiction, with a little jitter.
 *
 * A tariff is not a number in the abstract — it is a number in a currency, per
 * a unit, in a country whose units are not the same as anybody else's. Kenya
 * charges per cubic metre of water, the United States per gallon, so the rate
 * has to come from the profile rather than from a constant in the seeder.
 *
 * The jitter keeps a hundred tariffs from looking like a spreadsheet: two
 * properties on the same street do not get billed the identical rate to the
 * cent.
 */
export function utilityRate(
  profile: JurisdictionProfile,
  type: 'WATER' | 'ELECTRICITY' | 'GAS',
): number {
  const tariff = profile.utilityTariffs.find((t) => t.type === type);
  if (!tariff) return 0;
  // ±10%, and at least a hundredth of a unit so the rate is never zero.
  const jitter = 0.9 + Math.random() * 0.2;
  return Math.round(tariff.rate * jitter * 100) / 100;
}

export function randomFrom<T>(arr: T[]): T {
  return arr[r(arr.length)];
}

export function randomPhone(
  profile: JurisdictionProfile = activeProfile,
): string {
  const prefix = randomFrom(profile.phonePrefixes);
  const restLen = Math.max(1, profile.phoneSubscriberLength - prefix.length);
  const rest = String(
    Math.floor(Math.random() * Math.pow(10, restLen)),
  ).padStart(restLen, '0');
  // remove country code leading zero handling: just concatenate
  return `${profile.phoneCountryCode}${prefix}${rest}`.replace(/\s+/g, '');
}

