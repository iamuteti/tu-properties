export function randomEmail(
  name: string,
  profile: JurisdictionProfile = activeProfile,
): string {
  const domain = randomFrom(profile.domains);
  // The local part is folded to ASCII: a French or German name keeps its
  // accents in the data, but an email address carrying them is not something a
  // mail server will accept, and a demo address that bounces is a demo that
  // looks broken.
  const localPart =
    name
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/\s+/g, '.')
      .replace(/[^a-z0-9.]+/g, '')
      .replace(/\.{2,}/g, '.')
      .replace(/^\.|\.$/g, '') || 'resident';
  return `${localPart}@${domain}`;
}

